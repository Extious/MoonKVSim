#!/usr/bin/env python3
"""Validate/index the editable patent figures without rewriting user sources.

The .drawio files are authoritative. Native Draw.io exports supply DOCX images.
Historical generator versions are retained in the dated review snapshots.
"""
from pathlib import Path
import hashlib
import json
import xml.etree.ElementTree as E

OUT = Path(__file__).resolve().parent
STEMS = ('figure-2-agent-credit', 'figure-3-slacklandlord')


def inspect(stem):
    path = OUT / (stem + '.drawio')
    data = path.read_bytes()
    book = E.fromstring(data)
    graphs = book.findall('.//mxGraphModel')
    assert len(graphs) == 1, 'one uncompressed diagram expected'
    graph = graphs[0]
    cells = list(graph.iter('mxCell'))
    ids = [c.get('id') for c in cells]
    assert None not in ids and len(ids) == len(set(ids)), 'missing or duplicate cell IDs'
    edges, boxes = [], []
    for cell in cells:
        for attr in ('parent', 'source', 'target'):
            assert not cell.get(attr) or cell.get(attr) in ids, (cell.get('id'), attr)
        if cell.get('edge') == '1':
            assert cell.get('source') and cell.get('target')
            assert cell.find('mxGeometry') is not None
            edges.append([cell.get('source'), cell.get('target')])
        if cell.get('vertex') == '1':
            geo = cell.find('mxGeometry')
            assert geo is not None, cell.get('id')
            x, y, w, h = (float(geo.get(k, '0')) for k in ('x', 'y', 'width', 'height'))
            assert w > 0 and h > 0, cell.get('id')
            boxes.append((x, y, x + w, y + h))
    # Native exports include actual bounds; titles may lie above the page origin.
    bounds = [min(b[0] for b in boxes), min(b[1] for b in boxes),
              max(b[2] for b in boxes), max(b[3] for b in boxes)]
    assert path.read_bytes() == data, 'source changed while indexing'
    return {'stem': stem, 'canvas': [float(graph.get('pageWidth')), float(graph.get('pageHeight'))],
            'vertex_bounds': bounds, 'edges': edges,
            'source_sha256': hashlib.sha256(data).hexdigest(),
            'source_authority': 'editable .drawio; never regenerated by this helper'}


if __name__ == '__main__':
    result = [inspect(stem) for stem in STEMS]
    (OUT / 'STRUCTURE.json').write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps([{k: v for k, v in item.items() if k != 'edges'} for item in result], ensure_ascii=False))
