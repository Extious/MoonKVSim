const {chromium} = require('playwright');
const fs = require('fs');
const crypto = require('crypto');
const path = require('path');
(async () => {
  const root=process.cwd();
  const selection=JSON.parse(fs.readFileSync(path.join(root,'output/evaluation-redesign-20260909/paper-selection.json')));
  const expectedImages=selection.figures.filter(r=>r.primary).length;
  const expectedSingles=selection.layout_groups.filter(g=>g.length===1).length;
  const expectedPairs=selection.layout_groups.filter(g=>g.length===2).length;
  const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:1120,height:900},deviceScaleFactor:1});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const out=path.join(root,'tmp/pdfs/evaluation-markdown');fs.mkdirSync(out,{recursive:true});
  await page.goto('file://'+path.join(root,'output/pdf/aegiskv-evaluation-20260909/paper-story.html'));
  await page.evaluate(()=>document.fonts.ready);
  const math_ready=await page.evaluate(()=>document.documentElement.dataset.mathReady==='true');
  const display_equations=await page.locator('.math.block').count();
  const inline_equations=await page.locator('.math.inline').count();
  if(!math_ready||display_equations!==3||errors.length)throw new Error('Math rendering failed '+JSON.stringify(errors));
  const images=await page.locator('img').count();
  const loaded=await page.locator('img').evaluateAll(xs=>xs.every(x=>x.complete&&x.naturalWidth>0));
  if(images!==expectedImages||!loaded)throw new Error('Image count/load mismatch '+images);
  await page.screenshot({path:path.join(out,'page-top.png')});
  const rows=page.locator('table.figpair');
  for(let i=0;i<await rows.count();i++)await rows.nth(i).screenshot({path:path.join(out,'pair-'+(i+1)+'.png')});
  const singles=page.locator('figure.paper-figure');
  if(await singles.count()!==expectedSingles)throw new Error('Standalone figure count');
  for(let i=0;i<await singles.count();i++)await singles.nth(i).screenshot({path:path.join(out,'single-'+String(i+1).padStart(2,'0')+'.png')});
  const equations=page.locator('.math.block');
  for(let i=0;i<display_equations;i++)await equations.nth(i).screenshot({path:path.join(out,'equation-'+(i+1)+'.png')});
  const headings=page.locator('main h2');
  const sections=await headings.allTextContents();
  if(JSON.stringify(sections)!==JSON.stringify(['Motivation','System Design','Evaluation']))throw new Error('Draft sections');
  for(let i=0;i<3;i++){await headings.nth(i).scrollIntoViewIfNeeded();await page.screenshot({path:path.join(out,'section-'+(i+1)+'.png')});}
  const overflow=await page.evaluate(()=>({document:document.documentElement.scrollWidth,viewport:innerWidth}));
  if(overflow.document>overflow.viewport)throw new Error('Horizontal overflow');
  const pairedRows=await rows.evaluateAll(xs=>xs.map(x=>[...x.querySelectorAll('img')].map(im=>{const r=im.getBoundingClientRect();return{x:r.x,y:r.y,width:r.width,height:r.height};})));
  if(pairedRows.length!==expectedPairs)throw new Error('Unexpected pair count');
  for(const p of pairedRows)if(p.length!==2||Math.abs(p[0].y-p[1].y)>2)throw new Error('Misaligned images');
  const sha=p=>crypto.createHash('sha256').update(fs.readFileSync(path.join(root,p))).digest('hex');
  fs.writeFileSync(path.join(root,'output/evaluation-redesign-20260909/MARKDOWN_LAYOUT.json'),JSON.stringify({status:'RENDERED',source_sha256:sha('benchmark/AegisKV/experiments/Paper_Draft.md'),html_sha256:sha('output/pdf/aegiskv-evaluation-20260909/paper-story.html'),images,loaded,pairedRows,overflow,math_ready,display_equations,inline_equations,sections,standalone_figures:expectedSingles,renderer:'Chromium, markdown-it tables and KaTeX 0.16.22; not the client-specific Markdown renderer'},null,2)+'\n');
  console.log(JSON.stringify({images,loaded,paired_rows:pairedRows.length,overflow}));
  await page.goto('file://'+path.join(root,'output/pdf/aegiskv-evaluation-20260909/evaluation-design.html'));
  await page.evaluate(()=>document.fonts.ready);
  const designImages=await page.locator('img').count();
  const designLoaded=await page.locator('img').evaluateAll(xs=>xs.every(x=>x.complete&&x.naturalWidth>0));
  const designOverflow=await page.evaluate(()=>({document:document.documentElement.scrollWidth,viewport:innerWidth}));
  if(designImages!==4||!designLoaded||designOverflow.document>designOverflow.viewport||errors.length)throw new Error('Design layout failed');
  const designPairs=page.locator('table.figpair');
  if(await designPairs.count()!==2)throw new Error('Design pairs');
  for(let i=0;i<2;i++)await designPairs.nth(i).screenshot({path:path.join(out,'design-pair-'+(i+1)+'.png')});
  fs.writeFileSync(path.join(root,'output/evaluation-redesign-20260909/DESIGN_LAYOUT.json'),JSON.stringify({source_sha256:sha('benchmark/AegisKV/experiments/EVALUATION_DESIGN.md'),images:designImages,loaded:designLoaded,overflow:designOverflow},null,2)+'\n');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
