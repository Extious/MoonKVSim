#!/usr/bin/env python3
"""Compact Motivation trace plots, using the unchanged frozen inputs.

The workflow is generated by build_motivation_workflow.py; measured costs
use render_reuse_physical.py --layout compact. This script renders only the
workflow-maxima ECDF and the four independent recovery counterfactuals.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import importlib.util
import json
from pathlib import Path
from motivation_layout import HEIGHT_IN, WIDTHS_IN, axes_rect

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("motivation_row", HERE / "render_motivation_row.py")
row = importlib.util.module_from_spec(spec)
spec.loader.exec_module(row)
base, np, plt = row.base, row.np, row.plt


def branch_gap():
    with base.GAP_CSV.open() as stream:
        rows = list(csv.DictReader(stream))
    gap = np.sort([float(r["max_duration_gap_s"]) for r in rows])
    selection = json.loads(row.GAP_SELECTION.read_text())
    assert len(gap) == selection["retained_workflows"]
    median, p90 = np.median(gap), np.percentile(gap, 90)
    assert abs(median - selection["median_duration_gap_s"]) < 1e-9
    assert abs(p90 - selection["p90_duration_gap_s"]) < 1e-9
    fig = plt.figure(figsize=(WIDTHS_IN["workflow-gaps"], HEIGHT_IN))
    ax = fig.add_axes(axes_rect(WIDTHS_IN["workflow-gaps"], .54, .08))
    ax.step(np.r_[.3, gap, 3e4], np.r_[0, np.arange(1, len(gap)+1)/len(gap), 1],
            where="post", color=base.BLUE, lw=1.4)
    ax.hlines(.5, .3, median, color="#BCC7D0", lw=.65, ls=(0, (2, 3)))
    ax.plot(median, .5, "o", color=base.BLUE, ms=3.5)
    ax.hlines(.9, .3, p90, color="#BCC7D0", lw=.65, ls=(0, (2, 3)))
    ax.plot(p90, .9, "o", color=base.BLUE, mfc="white", ms=3.5)
    # Quantile labels occupy the same header band as the cost panel's legend.
    fig.text(.28, .978, f"Median\n{median:.0f} s", color=base.INK,
             ha="center", va="top", linespacing=1.2)
    fig.text(.77, .978, f"P90\n{p90:,.0f} s", color=base.INK,
             ha="center", va="top", linespacing=1.2)
    ax.set_xscale("log")
    ax.set_xlim(.3, 3e4)
    ax.set_ylim(0, 1.04)
    ax.set_xticks([1, 100, 10000], ["1", "100", "10k"])
    ax.minorticks_off()
    ax.set_yticks([0, .5, 1], ["0", "50", "100"])
    ax.set_xlabel("Max. gap (s)", labelpad=3)
    ax.set_ylabel("Workflows (%)", labelpad=2)
    ax.tick_params(length=2.5, pad=2)
    base.save(fig, "workflow-gaps", evidence="trace", width_in=2.0,
              note="Same 121 workflow maxima and unsmoothed ECDF; only layout changes. "
                   "Axes share the cost panel's physical top/bottom and xlabel baseline; quantiles occupy the header band. "
                   "Fan-in is temporally inferred, Main activity is allowed, and gaps are not failure-time slack.",
              sources=[str(p.relative_to(base.ROOT)) for p in (base.GAP_CSV, row.GAP_SELECTION)])
    return {"workflow_maxima_s": gap.tolist(), "median_s": median, "p90_s": p90}


def exposure():
    with base.CC_CSV.open() as stream:
        rows = list(csv.DictReader(stream))
    costs = json.loads(row.EXAMPLE_COSTS.read_text())["workflow_costs"]
    assert len(rows) == len(costs) == 4
    assert len({r["workflow_id"] for r in rows}) == 1
    assert all(c["branch_index"] == int(r["branch_index"]) and
               c["prefix_tokens"] == int(r["prefix_tokens"]) for c, r in zip(costs, rows))
    times = np.array([c["recompute_s"] for c in costs])
    slack = np.array([float(r["slack_s"]) for r in rows])
    exposed = np.maximum(times - slack, 0)
    absorbed = times - exposed
    fig = plt.figure(figsize=(3.34, 1.45))
    ax = fig.add_axes([.14, .28, .64, .54])
    stats = fig.add_axes([.82, .28, .17, .54], sharey=ax)
    y = np.arange(len(rows))
    ax.barh(y, absorbed, height=.60, color=base.PALE_GREEN, edgecolor=base.GREEN,
            hatch="//", lw=.6, label="Slack absorbs")
    ax.barh(y, exposed, left=absorbed, height=.60, color=base.RED, label="WCT loss")
    for i, (t, s) in enumerate(zip(times, slack)):
        ax.text(t+.55, i, f"{t:.1f}", ha="left", va="center")
        stats.text(.5, i, f"{s:.1f}", ha="center", va="center", color=base.GRAY)
    ax.set_yticks(y, [f"A{i+1}" for i in y])
    ax.set_ylim(3.5, -.5)
    ax.set_xlim(0, 50)
    ax.set_xticks([0, 20, 40])
    ax.set_xlabel("Recompute time (s)", labelpad=2)
    ax.set_ylabel("Agent", labelpad=2)
    ax.tick_params(axis="y", length=0, pad=2)
    ax.tick_params(axis="x", length=2.5, pad=2)
    ax.set_axisbelow(True)
    ax.grid(axis="x", color="#E3E7EB", lw=.6)
    stats.set_xlim(0, 1)
    stats.set_axis_off()
    stats.text(.5, 1.045, "Slack (s)", transform=stats.transAxes,
               ha="center", va="bottom", color=base.GRAY)
    fig.legend(*ax.get_legend_handles_labels(), loc="upper left",
               bbox_to_anchor=(.10, .97), ncol=2, handlelength=1.1,
               handletextpad=.4, columnspacing=.7, borderpad=0, borderaxespad=0)
    base.save(fig, "recovery-exposure", evidence="trace+static-estimate", width_in=3.34,
              note="Same four independent single-branch counterfactuals, costs and slack. "
                   "One-line legend and shorter axis region reduce whitespace; no data or model change. "
                   "Qwen3-14B/A100 BF16 static estimates, 64-token hash-block input proxy and assumed 64-token tail; "
                   "other execution and queueing fixed, not a simultaneous fault experiment.",
              sources=[str(p.relative_to(base.ROOT)) for p in (base.CC_CSV, row.SELECTION, row.EXAMPLE_COSTS)])
    return [dict(branch=f"A{i+1}", recompute_s=float(t), slack_s=float(s), exposed_s=float(e))
            for i, (t, s, e) in enumerate(zip(times, slack, exposed))]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    base.OUT = args.output_dir
    plt.rcParams.update({"font.size":10.25, "axes.labelsize":10.25,
                         "xtick.labelsize":10.25, "ytick.labelsize":10.25, "legend.fontsize":10.25})
    gaps, cases = branch_gap(), exposure()
    sources = (base.GAP_CSV, row.GAP_SELECTION, base.CC_CSV, row.SELECTION, row.EXAMPLE_COSTS)
    manifest = {"generator":str(Path(__file__).relative_to(base.ROOT)),
                "generator_sha256":hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                "layout_sha256":base.sha(HERE / "motivation_layout.py"),
                "source_sha256":{str(p.relative_to(base.ROOT)):base.sha(p) for p in sources},
                "gaps":gaps, "exposure_cases":cases, "figures":base.MANIFEST}
    (base.OUT / "trace-figures.json").write_text(json.dumps(manifest, indent=2)+"\n")
    print(json.dumps({name: value["size_in"] for name, value in base.MANIFEST.items()}))


if __name__ == "__main__":
    main()
